"""Publish one AbstractPlanningResultV1 as JSON + Markdown + model-card snippet (AP-037 / SLM-338).

Reads a result JSON (or merges a harness output directory of ``*.json`` fragments
with ``--from-dir``), refuses to publish while ``publication_blockers`` is
non-empty, then emits every artifact from that one object:

- canonical JSON (schema + content sha256) at ``<output>.json``
- narrative Markdown rendered from the JSON at ``<output>.md``
- a model-card roster row (``--snippet-out``, else stdout) — never auto-inserted
- optional append-only disposition section in
  ``docs/design/abstract-planning-evidence-contract.md`` keyed by campaign hash
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from slm_training.harnesses.autoresearch.planning_result import (
    AbstractPlanningResultV1,
    publication_blockers,
    render_markdown,
    render_model_card_row,
    stamp_version,
)


def _load_payload(source: Path, *, from_dir: bool) -> dict[str, Any]:
    if not from_dir:
        return json.loads(source.read_text(encoding="utf-8"))
    merged: dict[str, Any] = {}
    for fragment in sorted(source.glob("*.json")):
        merged.update(json.loads(fragment.read_text(encoding="utf-8")))
    if not merged:
        raise ValueError(f"no JSON fragments found in {source}")
    return merged


def _disposition_section(
    payload: dict[str, Any], *, content_sha: str, evidence_path: str
) -> str:
    return (
        f"## Campaign `{payload['campaign_manifest_sha256']}`\n\n"
        f"- Campaign id: `{payload['campaign_id']}`\n"
        f"- Claim class: **{payload['claim_class']}**\n"
        f"- Result content sha256: `{content_sha}`\n"
        f"- Evidence: `{evidence_path}`\n"
    )


def append_disposition(
    doc_path: Path, payload: dict[str, Any], *, content_sha: str, evidence_path: str
) -> bool:
    """Append a campaign-hash-keyed section; return True when the doc changed."""
    manifest_sha = payload["campaign_manifest_sha256"]
    existing = (
        doc_path.read_text(encoding="utf-8")
        if doc_path.is_file()
        else (
            "# Abstract planning evidence contract\n\n"
            "Append-only disposition log keyed by locked campaign manifest hash.\n"
            "Sections are generated by `scripts/publish_planning_result.py`; never hand-edit.\n"
        )
    )
    if f"## Campaign `{manifest_sha}`" in existing:
        return False
    text = (
        existing.rstrip("\n")
        + "\n\n"
        + _disposition_section(
            payload, content_sha=content_sha, evidence_path=evidence_path
        )
    )
    doc_path.parent.mkdir(parents=True, exist_ok=True)
    doc_path.write_text(text, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source",
        type=Path,
        help="result JSON file (or harness output dir with --from-dir)",
    )
    parser.add_argument(
        "--from-dir",
        action="store_true",
        help="merge all *.json fragments in the source directory",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="artifact prefix (default: abstract-planning-<campaign_id>)",
    )
    parser.add_argument(
        "--snippet-out",
        type=Path,
        default=None,
        help="model-card row destination (default: stdout)",
    )
    parser.add_argument(
        "--append-disposition",
        type=Path,
        default=None,
        help="append-only disposition doc to update",
    )
    args = parser.parse_args(argv)

    payload = _load_payload(args.source, from_dir=args.from_dir)
    result = AbstractPlanningResultV1.from_dict(payload)
    if not result.version_stamp:
        result = stamp_version(result)
    blockers = publication_blockers(result)
    if blockers:
        for blocker in blockers:
            print(f"publication blocked: {blocker}", file=sys.stderr)
        return 1

    canonical = result.to_dict()
    canonical["content_sha256"] = result.content_sha256()
    prefix = args.output or Path(f"abstract-planning-{result.campaign_id}")
    prefix.parent.mkdir(parents=True, exist_ok=True)
    json_path = prefix.with_suffix(".json")
    md_path = prefix.with_suffix(".md")
    json_path.write_text(
        json.dumps(canonical, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    md_path.write_text(render_markdown(canonical), encoding="utf-8")

    row = render_model_card_row(canonical, evidence_path=str(json_path)) + "\n"
    if args.snippet_out:
        args.snippet_out.parent.mkdir(parents=True, exist_ok=True)
        args.snippet_out.write_text(row, encoding="utf-8")
    else:
        sys.stdout.write(row)

    if args.append_disposition:
        changed = append_disposition(
            args.append_disposition,
            canonical,
            content_sha=canonical["content_sha256"],
            evidence_path=str(json_path),
        )
        print(
            f"disposition {'appended' if changed else 'already present'}: {args.append_disposition}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
