"""Bounded verifier-filtered teacher-admission wiring evidence for SLM-296 (AP-013).

SLM-296 asks for >= 500 accepted records generated by a capable
*separate-family* teacher, filtered through G0-G10 plus independent judgment
and human audit, then a matched-budget fine-tune with a grammar-on/off
evaluation. This sandbox has neither network access to a real external
teacher nor a GPU: SLM-266 (`docs/design/teacher-program-data.md`) already
measured that even a local CPU teacher run is infeasible here (an 8-token
probe took 95.65s; a 10k-request campaign would take >= 11 continuous days).

This module is a bounded, honest wiring slice instead: a deterministic
offline candidate proposer (explicitly *not* a real separate-family
teacher) feeds the real G0-G12 verifier stack (`slm_training.data.verify`),
tagged with the ``"teacher"`` weak source so tier assignment structurally
enforces "teacher self-judgment alone cannot assign Gold/Silver" (only
`human_audit_passed` reaches Gold; weak sources cap at Bronze regardless of
gate passes). It also exercises, with real pass/fail behavior:

* family independence -- a same-family "shadow judge" is shown to get its
  candidates quarantined by the G11 gate, never silently promoted;
* decontamination -- candidates whose canonical root collides with a locked
  holdout set are excluded from admission before counting yield.

No model is trained and no grammar-on/off delta is measured; the >= 500
accepted-record target is not attempted at this scale. This is wiring
evidence only.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import Any

from slm_training.data.progspec.generate import GeneratorConfig, ProgramGenerator
from slm_training.data.progspec.schema import ProgramSpec, emit_record
from slm_training.data.verify import Tier, VerificationContext, verify_record
from slm_training.harnesses.train_data.diversity import fingerprint_record

SCHEMA = "verified_teacher_admission_report/v1"
EXPERIMENT_ID = "slm296-verified-teacher-admission"
TEACHER_MODEL_FAMILY = "deterministic_programspec_generator_v1"

DEFAULT_CONFIG = GeneratorConfig(
    components=("TextContent", "Button", "Separator"),
    max_depth=3,
    max_width=3,
)


def _sha(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":"), default=str).encode()
    ).hexdigest()


def check_family_independence(
    teacher_model_family: str, judge_model_family: str | None
) -> bool | None:
    """Return whether a judge is independent of the teacher that proposed a candidate.

    ``None`` means no judge was supplied (the gate must SKIP, never PASS);
    ``False`` means the judge shares the teacher's model family (self-judgment,
    the gate must FAIL); ``True`` means the families differ.
    """
    if judge_model_family is None:
        return None
    return judge_model_family != teacher_model_family


def _propose_candidates(
    config: GeneratorConfig, *, seeds: tuple[int, ...]
) -> list[ProgramSpec]:
    """Deterministic offline candidate proposer standing in for a teacher.

    Multiple seeds emulate multi-sample decoding from a real teacher. This is
    the repository's own verified generator (SLM-5), not a separate-family
    model -- every candidate is tagged with source ``"teacher"`` downstream so
    the real verifier stack treats it as an unproven weak source regardless.
    """
    specs: list[ProgramSpec] = []
    for seed in seeds:
        generator = ProgramGenerator(config, seed=seed)
        for _ in range(config.max_depth * config.max_width):
            try:
                specs.append(generator.generate_one())
            except ValueError as exc:
                if str(exc) == "candidate grid exhausted":
                    break
                raise
    return specs


def _teacher_record(spec: ProgramSpec):
    return emit_record(
        spec,
        prompt="Generate this typed OpenUI program.",
        task="generation",
        source="teacher",
        provenance={"teacher_model_family": TEACHER_MODEL_FAMILY},
    )


@dataclass(frozen=True)
class AdmissionRowV1:
    candidate_id: str
    canonical_root_id: str
    tier: str
    failing_gate: str | None
    locked_set_overlap: bool

    def to_dict(self) -> dict[str, Any]:
        return {
            "candidate_id": self.candidate_id,
            "canonical_root_id": self.canonical_root_id,
            "tier": self.tier,
            "failing_gate": self.failing_gate,
            "locked_set_overlap": self.locked_set_overlap,
        }


def run_verified_teacher_admission(
    *,
    seeds: tuple[int, ...] = (0, 1, 2),
    config: GeneratorConfig | None = None,
    locked_holdout_seed: int = 999,
) -> dict[str, Any]:
    """Run the bounded verifier-filtered teacher-admission wiring campaign."""
    cfg = config or DEFAULT_CONFIG
    proposed_specs = _propose_candidates(cfg, seeds=seeds)

    # Decontamination: a locked holdout drawn from a disjoint seed so its
    # canonical roots may legitimately collide with proposed candidates.
    holdout_specs = _propose_candidates(cfg, seeds=(locked_holdout_seed,))
    locked_roots = {
        fingerprint_record(_teacher_record(spec)).canonical_root_id
        for spec in holdout_specs
    }

    rows: list[AdmissionRowV1] = []
    accepted_roots: set[str] = set()
    tier_counts: dict[str, int] = {}
    gate_failure_counts: dict[str, int] = {}
    locked_set_overlap_rejected = 0

    for spec in proposed_specs:
        record = _teacher_record(spec)
        root_id = fingerprint_record(record).canonical_root_id
        overlap = root_id in locked_roots
        if overlap:
            locked_set_overlap_rejected += 1
            rows.append(
                AdmissionRowV1(
                    candidate_id=record.id,
                    canonical_root_id=root_id,
                    tier="excluded_locked_set_overlap",
                    failing_gate=None,
                    locked_set_overlap=True,
                )
            )
            continue
        # independent_judge_passed=None: no real external judge is available;
        # the gate must SKIP, never fabricate a PASS.
        report = verify_record(
            record,
            VerificationContext(source_kind="teacher", independent_judge_passed=None),
        )
        tier_counts[report.tier.name] = tier_counts.get(report.tier.name, 0) + 1
        failing_gate = report.failing_gate.value if report.failing_gate else None
        if failing_gate:
            gate_failure_counts[failing_gate] = (
                gate_failure_counts.get(failing_gate, 0) + 1
            )
        if report.ok:
            accepted_roots.add(root_id)
        rows.append(
            AdmissionRowV1(
                candidate_id=record.id,
                canonical_root_id=root_id,
                tier=report.tier.name,
                failing_gate=failing_gate,
                locked_set_overlap=False,
            )
        )

    accepted = sum(
        1 for row in rows if row.tier != "QUARANTINE" and not row.locked_set_overlap
    )
    gold_or_silver = sum(
        1
        for row in rows
        if row.tier in {Tier.GOLD.name, Tier.SILVER.name} and not row.locked_set_overlap
    )

    # Family-independence control: a same-family "shadow judge" must never
    # promote a candidate. Re-verify a small sample with independent_judge_passed
    # wired from check_family_independence(same family) -> False -> gate FAILs.
    shadow_sample = proposed_specs[: min(10, len(proposed_specs))]
    same_family_independent = check_family_independence(
        TEACHER_MODEL_FAMILY, TEACHER_MODEL_FAMILY
    )
    diff_family_independent = check_family_independence(
        TEACHER_MODEL_FAMILY, "external_model_family_v1"
    )
    shadow_quarantined = 0
    for spec in shadow_sample:
        record = _teacher_record(spec)
        report = verify_record(
            record,
            VerificationContext(
                source_kind="teacher",
                independent_judge_passed=same_family_independent,
            ),
        )
        if report.tier is Tier.QUARANTINE:
            shadow_quarantined += 1

    payload: dict[str, Any] = {
        "schema": SCHEMA,
        "experiment_id": EXPERIMENT_ID,
        "claim_class": "wiring",
        "recipe": {
            "seeds": list(seeds),
            "components": list(cfg.components or ()),
            "teacher_model_family": TEACHER_MODEL_FAMILY,
            "locked_holdout_seed": locked_holdout_seed,
        },
        "counts": {
            "proposed": len(proposed_specs),
            "locked_set_overlap_rejected": locked_set_overlap_rejected,
            "accepted": accepted,
            "accepted_gold_or_silver": gold_or_silver,
            "unique_accepted_canonical_roots": len(accepted_roots),
            "tier_counts": tier_counts,
            "gate_failure_counts": gate_failure_counts,
        },
        "family_independence_control": {
            "same_family_independent": same_family_independent,
            "different_family_independent": diff_family_independent,
            "shadow_judge_sample_size": len(shadow_sample),
            "shadow_judge_quarantined": shadow_quarantined,
            "shadow_judge_fully_quarantined": shadow_quarantined == len(shadow_sample),
        },
        "rows": [row.to_dict() for row in rows],
        "status": "yield_limitation_no_real_teacher_available",
        "limitations": [
            "No real separate-family teacher is available (no network/GPU in "
            "this sandbox); candidates come from the repository's own "
            "deterministic ProgramSpec generator, explicitly not a teacher. "
            "SLM-266 already measured that a local CPU teacher run is "
            "infeasible here (>= 11 days extrapolated for 10k requests).",
            "The >= 500 accepted-record target is not attempted at this "
            "scale; this is a bounded wiring campaign only.",
            "No fine-tuning run occurs and no grammar-off/meaning-v2 delta "
            "is measured or claimed.",
            "Gold/Silver promotion is structurally blocked here because "
            "'teacher' is a weak source with no human_audit_passed evidence "
            "-- every accepted row is Bronze at best, by construction of "
            "the real verifier stack, not by a claim made in this report.",
        ],
    }
    payload["manifest_hash"] = _sha(
        {key: value for key, value in payload.items() if key != "manifest_hash"}
    )
    return payload


def render_markdown(report: dict[str, Any]) -> str:
    counts = report["counts"]
    control = report["family_independence_control"]
    lines = [
        "# SLM-296 (AP-013): verifier-filtered teacher-admission wiring evidence",
        "",
        "**Claim class:** wiring / fixture only",
        "",
        f"**Status:** `{report['status']}`",
        "",
        "## Recipe",
        "",
        f"```json\n{json.dumps(report['recipe'], indent=2)}\n```",
        "",
        "## Admission counts",
        "",
        "| metric | value |",
        "| --- | --- |",
    ]
    for key in (
        "proposed",
        "locked_set_overlap_rejected",
        "accepted",
        "accepted_gold_or_silver",
        "unique_accepted_canonical_roots",
    ):
        lines.append(f"| {key} | {counts[key]} |")
    lines.append(f"| tier_counts | {counts['tier_counts']} |")
    lines.append(f"| gate_failure_counts | {counts['gate_failure_counts']} |")
    lines.extend(
        [
            "",
            "## Family-independence control",
            "",
            f"- same-family judge independent: {control['same_family_independent']}",
            f"- different-family judge independent: "
            f"{control['different_family_independent']}",
            f"- shadow-judge sample fully quarantined: "
            f"{control['shadow_judge_fully_quarantined']} "
            f"({control['shadow_judge_quarantined']}/"
            f"{control['shadow_judge_sample_size']})",
            "",
            "## Limitations",
            "",
        ]
    )
    lines.extend(f"- {item}" for item in report["limitations"])
    lines.append("")
    return "\n".join(lines)


